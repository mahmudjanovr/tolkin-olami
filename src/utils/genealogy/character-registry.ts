/**
 * Berilgan character_id boʻyicha qahramonning kanonik metamaʼlumotlarini qaytaradi.
 * Agar registrda mavjud boʻlmasa, xavfsiz zaxira obyekt qaytaradi.
 */
export function getCharacterMeta(characterId: string): CharacterRegistryEntry {
  const entry = CHARACTER_REGISTRY[characterId];
  if (entry) return entry;

  const fallbackName = characterId
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');

  return {
    id: characterId,
    name: fallbackName,
    titles: [],
    dates: 'Nomaʼlum',
    culture: 'Oʻrta-yer',
    race: 'insonlar',
    houseId: 'noma-lum',
    summary: `${fallbackName} — Tolkien asarlaridagi kanonik sulolaviy shaxs.`,
    textualStatus: 'posthumous_edited',
    citation: {
      work: 'The Lord of the Rings',
      section: 'Appendices',
    },
  };
}
